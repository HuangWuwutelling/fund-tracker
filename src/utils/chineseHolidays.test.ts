import { describe, it, expect } from 'vitest';
import dayjs from 'dayjs';
import { isNonTradingDay } from './chineseHolidays';

/**
 * 收集某年全部"工作日法定节假日"（周末由 isWeekend 统一判非交易日，不在此列）。
 * 用它做金标准比对：字典里多一个日期、少一个日期、日期写错一个字符都会红。
 */
function weekdayHolidays(year: number): string[] {
  const out: string[] = [];
  const end = dayjs(`${year + 1}-01-01`);
  for (let d = dayjs(`${year}-01-01`); d.isBefore(end); d = d.add(1, 'day')) {
    const dow = d.day(); // 0 = 周日
    if (dow !== 0 && dow !== 6 && isNonTradingDay(d.format('YYYY-MM-DD'))) {
      out.push(d.format('YYYY-MM-DD'));
    }
  }
  return out;
}

describe('isNonTradingDay（中国 A 股 / QDII 非交易日）', () => {
  it('2025 年工作日法定节假日与国办安排一致（国办发明电〔2024〕12 号）', () => {
    expect(weekdayHolidays(2025)).toEqual([
      '2025-01-01',
      '2025-01-28', '2025-01-29', '2025-01-30', '2025-01-31',
      '2025-02-03', '2025-02-04',
      '2025-04-04',
      '2025-05-01', '2025-05-02', '2025-05-05',
      '2025-06-02',
      '2025-10-01', '2025-10-02', '2025-10-03',
      '2025-10-06', '2025-10-07', '2025-10-08',
    ]);
  });

  it('2026 年工作日法定节假日与国办安排一致（2025-11-04 公布）', () => {
    expect(weekdayHolidays(2026)).toEqual([
      '2026-01-01', '2026-01-02',
      '2026-02-16', '2026-02-17', '2026-02-18', '2026-02-19', '2026-02-20', '2026-02-23',
      '2026-04-06',
      '2026-05-01', '2026-05-04', '2026-05-05',
      '2026-06-19',
      '2026-09-25',
      '2026-10-01', '2026-10-02',
      '2026-10-05', '2026-10-06', '2026-10-07',
    ]);
  });

  it('2027 年工作日法定节假日与国办安排一致（2026-11-05/06 公布）', () => {
    expect(weekdayHolidays(2027)).toEqual([
      '2027-01-01',
      '2027-02-05',
      '2027-02-08', '2027-02-09', '2027-02-10', '2027-02-11', '2027-02-12',
      '2027-04-05',
      '2027-05-03', '2027-05-04', '2027-05-05',
      '2027-06-09',
      '2027-09-15',
      '2027-10-01',
      '2027-10-04', '2027-10-05', '2027-10-06', '2027-10-07',
    ]);
  });

  it('周末一律为非交易日', () => {
    expect(isNonTradingDay('2027-01-02')).toBe(true); // 周六
    expect(isNonTradingDay('2027-01-03')).toBe(true); // 周日
  });

  it('普通工作日为交易日', () => {
    expect(isNonTradingDay('2027-01-04')).toBe(false); // 元旦后第一个工作日
    expect(isNonTradingDay('2027-02-15')).toBe(false); // 春节后复工
    expect(isNonTradingDay('2027-10-08')).toBe(false); // 国庆后第一个工作日
  });

  it('2027 春节假期整段都算非交易日（含衔接进来的周末）', () => {
    // 官方安排 2/5（除夕）至 2/13（正月初八）
    for (const d of ['2027-02-05', '2027-02-06', '2027-02-07', '2027-02-08', '2027-02-09',
      '2027-02-10', '2027-02-11', '2027-02-12', '2027-02-13']) {
      expect(isNonTradingDay(d)).toBe(true);
    }
    expect(isNonTradingDay('2027-02-15')).toBe(false); // 2/14 周日上班、2/15 周一复工
  });

  it('调休补班日（周末）仍判非交易日——QDII 当天不发 NAV', () => {
    // 2027 补班日：1/31（日）、2/14（日）、5/8（六）、9/26（日）、10/9（六）
    for (const d of ['2027-01-31', '2027-02-14', '2027-05-08', '2027-09-26', '2027-10-09']) {
      expect(isNonTradingDay(d)).toBe(true);
    }
  });

  it('2028 未收录 → 退化为"仅按周末判定"（不再假装精确）', () => {
    expect(isNonTradingDay('2028-01-01')).toBe(true);  // 周六
    expect(isNonTradingDay('2028-01-03')).toBe(false); // 周一（元旦未收录）
    expect(isNonTradingDay('2028-07-04')).toBe(false); // 周二（未收录年份不判定节假日）
  });
});
