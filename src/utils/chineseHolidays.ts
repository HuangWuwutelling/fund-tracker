/**
 * 中国 A 股 / QDII 交易日判定（基于国务院办公厅年度公告）。
 *
 * 数据维护窗口：2025-2026。每年 10 月底前需补下一年数据
 * （下一年度放假安排通常在 10 月底由国务院办公厅公布）。
 *
 * 数据源：
 * - 国务院办公厅关于 2025 年部分节假日安排的通知（国办发明电〔2024〕12 号）
 * - 国务院办公厅关于 2026 年部分节假日安排的通知（2025-11-04 公布）
 *
 * 判定规则：
 *   非交易日 = 周末 ∪ 法定节假日（工作日部分）
 * - 周末（含被假期块自然衔接进去的周六/周日）默认是非交易日
 * - 调休补班的周末（A 股照常开市）也视为非交易日——
 *   A 股虽然交易，但 QDII 基金公司当天不发布 NAV（参考 2025-10-11），
 *   统一按非交易日处理可让日历格子的休市着色与 QDII 实际节奏一致
 * - 工作日的法定节假日单独列入 HOLIDAYS 集合
 *
 * 超过 2026 年的数据暂未公布——isNonTradingDay 对未知年份退化为「仅按周末判定」。
 */

